function buildPaint(damageType: Vehicle['damageType']): PaintReading[] {
  return [
    { panelKey: 'hood', microns: damageType === 'Front End' ? 245 : 112, status: damageType === 'Front End' ? 'repainted' : 'factory' },
    { panelKey: 'roof', microns: damageType === 'Hail / Weather' ? 195 : 108, status: damageType === 'Hail / Weather' ? 'repainted' : 'factory' },
    { panelKey: 'frontLeftFender', microns: damageType === 'Front End' ? 290 : 115, status: damageType === 'Front End' ? 'replaced' : 'factory' },
    { panelKey: 'frontRightFender', microns: 114, status: 'factory' },
    { panelKey: 'leftDoors', microns: 118, status: 'factory' },
    { panelKey: 'rightDoors', microns: 116, status: 'factory' },
    { panelKey: 'rearLeftQuarter', microns: damageType === 'Rear Quarter' ? 260 : 119, status: damageType === 'Rear Quarter' ? 'repainted' : 'factory' },
    { panelKey: 'rearRightQuarter', microns: 117, status: 'factory' },
    { panelKey: 'trunk', microns: 111, status: 'factory' },
  ];
}

